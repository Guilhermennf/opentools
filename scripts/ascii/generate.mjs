// Regenerates every ASCII illustration from the scenes in scenes.mjs.
// Usage: pnpm ascii
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { render } from "./engine.mjs";
import * as scenes from "./scenes.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

const targets = {
  home: "apps/web/src/lib/home-ascii.ts",
  hash: "packages/tools/developer/hash-generator/src/ascii.ts",
  json: "packages/tools/developer/json-formatter/src/ascii.ts",
  media: "packages/tools/media/media-converter/src/ascii.ts",
};

for (const [name, rel] of Object.entries(targets)) {
  const lines = render(scenes[name]);
  const exportName = name === "home" ? "homeAscii" : "ascii";
  const body = `// Generated by scripts/ascii/generate.mjs (scene "${name}"). Do not edit by hand.\nexport const ${exportName} = [\n${lines.map((l) => `  ${JSON.stringify(l)},`).join("\n")}\n].join("\\n");\n`;
  fs.writeFileSync(path.join(root, rel), body);
  console.log(`${rel}: ${lines.length} rows`);
}
